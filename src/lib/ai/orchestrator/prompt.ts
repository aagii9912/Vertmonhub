const DOMAIN_NOTES = `ДОМЭЙНЫ ТЭМДЭГЛЭЛ:
- Лидийн статус: new → contacted → viewing_scheduled → offered → negotiating → closed_won / closed_lost. «Алдсан» болгоход шалтгаан (lost_reason) хэрэгтэй.
- Гэрээний процесс: sign (гэрээ → байр reserved, лид negotiating), paid (төлбөр → sold, closed_won), cancel (→ available, closed_lost).
- Ээлж→блок→нэгж бүтэцтэй бодит нөөц property_units-д; нэгжийн статусыг update_unit_status-аар (код/блокоор). update_property_status зөвхөн зурагтай listing-д.
- Уулзалт товлоход лид (нэр/утас) + огноо цаг + байр (заавал биш) хэрэгтэй; уулзалт нь нэвтэрсэн менежерийн нэрээр бүртгэгдэнэ. Уулзалт болсны дараа record_viewing_outcome; «Болдтой ярилаа, маргааш дахин залгана» → log_call (next_followup_at-тай).
- Огноо/цагийг ISO 8601 +08:00-оор өг («маргааш 10 цаг» → ОДОО-гоос тооцоол). Харьцангуй огноог өөрөө тооцоол, хэрэглэгчээс бүү асуу.
- Хавсаргасан зураг/PDF-ийг харж агуулгыг нь ашигла; бичлэгт хавсаргах бол attach_file-д яг өгөгдсөн URL-ийг өг.`;

/** Тогтмол (cache-лэгдэх) + хувьсах систем блокууд. */
export function buildSystemBlocks(ctx: OrchestratorContext, extra?: { personaOverride?: string; includeDomainNotes?: boolean }): Anthropic.TextBlockParam[] {
    const stable = [extra?.personaOverride ?? ASSISTANT_PERSONA, extra?.includeDomainNotes === false ? '' : DOMAIN_NOTES].filter(Boolean).join('\n\n');
    const blocks: Anthropic.TextBlockParam[] = [
        { type: 'text', text: stable, cache_control: { type: 'ephemeral', ttl: '1h' } },
    ];
    // Shop мэдлэг + урт хугацааны санах ой — session дотор тогтмол тул мөн cache-лэнэ.
    if (ctx.shopKnowledge) {
        blocks.push({ type: 'text', text: `КОМПАНИЙН МЭДЛЭГ:\n${ctx.shopKnowledge}`, cache_control: { type: 'ephemeral', ttl: '1h' } });
    }
    const volatile: string[] = [];
    const now = new Date();
    const ub = new Intl.DateTimeFormat('sv-SE', { timeZone: 'Asia/Ulaanbaatar', dateStyle: 'short', timeStyle: 'short' }).format(now);
    volatile.push(`ОДОО: ${ub} (Улаанбаатар).`);
    volatile.push(`ХЭРЭГЛЭГЧ: ${ctx.userName || 'нэр тодорхойгүй'}, эрх: ${ctx.perms.role}${ctx.perms.canWrite ? ', бичих эрхтэй' : ', зөвхөн унших'}${ctx.perms.canDelete ? ', устгах эрхтэй' : ''}.`);
    if (ctx.conversationSummary) volatile.push(`ЭНЭ ЯРИАНЫ ӨМНӨХ ХЭСГИЙН ХУРААНГУЙ:\n${ctx.conversationSummary}`);
    blocks.push({ type: 'text', text: volatile.join('\n') });
    return blocks;
}
